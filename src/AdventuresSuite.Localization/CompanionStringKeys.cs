namespace AdventuresSuite.Localization;

/// <summary>
/// Defines stable resource keys for shared Companion chrome.
/// </summary>
public static class CompanionStringKeys
{
    /// <summary>Gets the resource key for the application name.</summary>
    public const string AppName = nameof(AppName);

    /// <summary>Gets the resource key for the initial loading message.</summary>
    public const string PreparingAdventure = nameof(PreparingAdventure);

    /// <summary>Gets the resource key for the Adventure label.</summary>
    public const string Adventure = nameof(Adventure);

    /// <summary>Gets the resource key for the current-Adventure state.</summary>
    public const string Current = nameof(Current);

    /// <summary>Gets the resource key for the planned-Adventure state.</summary>
    public const string Planned = nameof(Planned);

    /// <summary>Gets the resource key for the offline state.</summary>
    public const string Offline = nameof(Offline);

    /// <summary>Gets the resource key for Home navigation.</summary>
    public const string NavigationHome = nameof(NavigationHome);

    /// <summary>Gets the resource key for Journey navigation.</summary>
    public const string NavigationJourney = nameof(NavigationJourney);

    /// <summary>Gets the resource key for readiness navigation.</summary>
    public const string NavigationReady = nameof(NavigationReady);

    /// <summary>Gets the resource key for Memories navigation.</summary>
    public const string NavigationMemories = nameof(NavigationMemories);
}
